"""What technology a directory is, and what that means for reading it.

Every exclusion this tool has was added after a false-positive class turned
up in someone's project: `.tsx` skipped and then un-skipped (`P-19`), PHP
masked (three WordPress themes), `wp-admin/` excluded (455 findings in
vendored WordPress core). Each was correct and each was reactive, which means
the next stack fails the same way before anyone notices.

That is the thing this module fixes. A repository announces what it is -
`wp-config.php`, `artisan`, `next.config.js`, `manage.py` - and what it is
decides two things a scan otherwise has to guess:

* **what is not the product.** `vendor/` in a Laravel app, `wp-includes/` in
  a WordPress install and `.svelte-kit/` in a SvelteKit app are all code
  somebody else wrote or a build step emitted. Auditing them reports real
  defects against files the developer cannot change, which buries the ones
  they can.
* **what the markup is written in.** A `.php` file is a template with server
  tags; a `.tsx` file is JSX. Both need masking before an HTML parser sees
  them, and the masks differ.

Two rules hold everything here honest:

**Detection is evidence, never a guess.** A profile names the file that
proved it, and `Profile.evidence` travels into the report. A stack nobody can
point at a marker file for is simply not detected, and the scan falls back to
the defaults - which is the behaviour that already worked.

**An exclusion must be about ownership, not about names.** `dist/` earns its
place because a bundler wrote it. A directory is never excluded for looking
unimportant: `repo_scanner`'s own comment records that guessing at `lib/`
blinded the scanner to 67 real findings in xFormat.
"""
from __future__ import annotations

import json
