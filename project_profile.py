#: Files whose first lines say a machine wrote them. Checked ahead of any
#: stack, because the marker is a convention rather than a technology:
#: protobuf, GraphQL codegen, OpenAPI clients, Prisma, i18n extractors and
#: `.d.ts` emitters all write one, and none of them is a file anyone edits.
#:
#: A finding in a generated file is not wrong, it is unactionable - the fix
#: belongs in the generator, and the file is overwritten on the next build.
_GENERATED_MARKERS = (
    "do not edit",
    "do not modify",
    "auto-generated",
    "autogenerated",
    "automatically generated",
    "generated by",
    "@generated",
    "code generated by",
)
#: How far into a file to look for one. Every convention puts the marker in a
#: header comment; scanning further would read whole files to find a phrase
#: that legitimately appears in prose.
_GENERATED_HEAD = 600


def looks_generated(text: str) -> bool:
    """Does this file say a machine wrote it?

    Deliberately narrow: the marker has to be near the top, where every
    generator convention puts it. A README that discusses generated code
    mentions the phrase in its body and is not caught.
    """
    head = text[:_GENERATED_HEAD].lower()
    return any(marker in head for marker in _GENERATED_MARKERS)


