_COMPILED = tuple(
    (sig, re.compile(sig.pattern, re.IGNORECASE)) for sig in _SIGNATURES
)

#: Combined confidence a stack has to reach before it is named.
_DETECTED_AT = 100


def _stack_by_name(name: str) -> Stack:
    for stack in STACKS:
        if stack.name == name:
            return stack
    return Stack(name, why="identified from the served markup", hosted=True)


def detect_from_markup(markup: str) -> Profile:
    """What a served page says built it, on signatures alone.

    A signature is a literal that platform emits - never an inference from
    layout, class names or "feel". Weak signatures accumulate: two 50s name a
    platform, one 50 does not. A page carrying nothing is undetected, which is
    what most hand-built sites are and what the scan already handles.

    Several platforms can be true at once and all are kept. A WordPress site
    served through Shopify's CDN is two facts, and picking one would throw the
    other away.
    """
    profile = Profile(root="")
    text = markup or ""
    scores: dict = {}
    reasons: dict = {}
    versions: dict = {}

    for sig, pattern in _COMPILED:
        match = pattern.search(text)
        if not match:
            continue
        scores[sig.stack] = scores.get(sig.stack, 0) + sig.confidence
        reasons.setdefault(sig.stack, []).append(sig.why)
        if sig.version_group and not versions.get(sig.stack):
            try:
                found = (match.group(sig.version_group) or "").strip()
            except (IndexError, error):
                found = ""
            if found:
                versions[sig.stack] = found

    for name, score in scores.items():
        if score < _DETECTED_AT:
            continue
        profile.stacks.append(_stack_by_name(name))
        evidence = " + ".join(reasons[name])
        if name in versions:
            evidence = f"{evidence} (version {versions[name]})"
        profile.evidence[name] = evidence
        profile.versions[name] = versions.get(name, "")
    return profile


#: Code a platform injects into the page **itself**, per stack. One test
#: decides membership, and it is not "did the author type this": it is
#: **can the site owner change it at all**.
#:
#: What this is for: a finding inside markup the platform generated is not the
#: site owner's to fix. A WordPress site is told about render-blocking
#: stylesheets, and they are `wp-includes/blocks/*/style.min.css`, enqueued by
#: core - the owner can no more remove them than they can edit someone else's
#: server. Reporting that as their problem is the report being technically
#: right and practically useless, which is how a tool trains people to skim.
#:
#: Every entry here was measured against a live site, and measuring is what
#: emptied most of the list:
#:
#: * **A CDN is not a platform.** `cdn.shopify.com` was in this table until a
#:   run on `shopify.com` attributed 20 findings to Shopify - most of them
#:   `<video>` elements with no captions, whose only Shopify-ness was where
#:   the poster image was hosted. A merchant's own uploads sit on that host
#:   too. Only `shopifycloud`, which is storefront code nobody can edit,
#:   survived. The same removed `static.wixstatic.com`, `media.beehiiv.com`
#:   and `website-files.com`.
#: * **A build is the author's.** `/_next/static/`, `/_nuxt/`,
#:   `/_app/immutable/` are the author's own code compiled, so Next, Nuxt and
#:   SvelteKit own nothing - and neither do Hugo, Jekyll, Astro, Vite or
#:   Eleventy, which is why no generator appears here at all. Detecting Hugo
#:   says something about the project; it says nothing about who owns a
#:   finding.
#: * **A theme is chosen and editable**, so `wp-content/themes/` is the
#:   owner's responsibility even when they did not type it. A plugin is
#:   chosen too, but its markup cannot be changed without forking it, so it
#:   stays here.
#:
#: Nothing is ever suppressed by this. The finding is reported either way -
#: a rule that removes a real finding makes a scan quieter and worse - and
#: what changes is only who is named as able to act on it.
PLATFORM_ASSETS: dict = {
    "wordpress": ("/wp-includes/", "/wp-content/plugins/", "/wp-json/",
                  "wp-emoji-release.min.js"),
    "drupal": ("/core/misc/", "/core/modules/", "/core/assets/"),
    "joomla": ("/media/jui/", "/media/system/js/"),
    "typo3": ("/typo3temp/", "/typo3conf/"),
    "shopify": ("shopifycloud",),
    "wix": ("static.parastorage.com",),
    "squarespace": ("assets.squarespace.com/universal",),
    "ghost": ("/public/cards.min.",),
    "spfx": ("/_layouts/15/",),
}


def platform_owner(stack_names, text: str) -> str:
    """Which detected platform emitted this markup, or `""` for the author.

    `text` is the offending markup itself, so the answer rests on the same
    kind of evidence the detection does: a literal path that is in the
    element or is not. An element carrying no address - a heading with a
    contrast problem, a field with no label - belongs to whoever wrote the
    page, which is the answer this returns by staying empty.
    """
    if not text:
        return ""
    haystack = text.lower()
    for name in stack_names:
        for fragment in PLATFORM_ASSETS.get(name, ()):
            if fragment.lower() in haystack:
                return name
    return ""


@dataclass
class Profile:
    """What a directory turned out to be."""
    root: str = ""
    stacks: list = field(default_factory=list)
    #: `stack name -> the marker path that proved it`. Kept so the report can
    #: say why a directory was skipped, and so a wrong answer is arguable
    #: rather than mysterious.
    evidence: dict = field(default_factory=dict)
    #: `stack name -> version`, where the markup carried one. "WordPress" is a
    #: guess someone has to verify; "WordPress 7.1" is a fact they can act on.
    versions: dict = field(default_factory=dict)

    def excludes(self) -> list:
        """Every stack's exclusions, in detection order, without repeats."""
        seen: list = []
        for stack in self.stacks:
            for pattern in stack.excludes:
                if pattern not in seen:
                    seen.append(pattern)
        return seen

    def applied_to(self, patterns) -> list:
        """`patterns`, plus this profile's exclusions, without repeats.

        One function rather than the same three lines in every surface. The
        CLI had them and the window did not, which is why a folder audited
        from the window walked into `wp-includes/` and reported hundreds of
        findings against code the developer cannot change, while the same
        folder audited from `xanalyze audit` did not.
        """
        merged = list(patterns or [])
        for pattern in self.excludes():
            if pattern not in merged:
                merged.append(pattern)
        return merged

    def describe(self) -> str:
        """One line for the run's own output. Empty when nothing matched."""
        if not self.stacks:
            return ""
        names = ", ".join(stack.name for stack in self.stacks)
        return f"detected: {names}"

    def reasons(self) -> list:
        return [f"{stack.name}: {stack.why} (found {self.evidence[stack.name]})"
                for stack in self.stacks if stack.name in self.evidence]


#: How far below the target to look for a marker. A monorepo keeps its
#: applications one or two levels down - `apps/web/vite.config.ts`,
#: `web/wp-config.php`, `trasparenza/composer.json` - and scanning the
#: repository root is the normal thing to do. Every real project on this
#: machine except one was invisible at depth 0.
#:
#: Bounded, and it has to be: an unbounded walk would find a marker inside a
#: fixture, a vendored copy or a test project and apply that stack's
#: exclusions to the whole repository. Two levels is what a monorepo layout
#: costs; anything deeper is somebody else's project living inside this one.
_MARKER_DEPTH = 2

#: Directories never searched for markers, because a marker found in one
#: describes something other than the project: a vendored dependency's own
#: config, or a fixture built to look like a stack.
_MARKER_BLIND = {"node_modules", "vendor", "dist", "build", "out", ".git",
                 ".next", ".nuxt", ".svelte-kit", "__pycache__", "venv",
                 ".venv", "fixtures", "__fixtures__", "testdata"}


def _search_roots(root: Path) -> list:
    """`root` and the directories under it worth looking in, nearest first."""
    roots = [root]
    frontier = [root]
    for _level in range(_MARKER_DEPTH):
        nxt = []
        for parent in frontier:
            try:
                children = sorted(p for p in parent.iterdir() if p.is_dir())
            except OSError:
                continue
            for child in children:
                if child.name in _MARKER_BLIND or child.name.startswith("."):
                    continue
                roots.append(child)
                nxt.append(child)
        frontier = nxt
    return roots


#: How much of a file is read looking for a content marker. The headers
#: these look for are the first thing in the file by definition - WordPress
#: itself only reads the first 8 KB of `style.css` - so anything past this
#: is not a header, it is a coincidence.
_CONTENT_MARKER_BYTES = 8192


def _content_marker_present(root: Path, marker) -> bool:
    """Is there a file here whose *content* proves this stack?"""
    import re as _re

    path_pattern, pattern = marker
    candidates = (sorted(root.glob(path_pattern))[:20] if "*" in path_pattern
                  else [root / path_pattern])
    expression = _re.compile(pattern, _re.M | _re.I)
    for candidate in candidates:
        try:
            if not candidate.is_file():
                continue
            head = candidate.read_text(encoding="utf-8", errors="replace")
        except OSError:
            continue
        if expression.search(head[:_CONTENT_MARKER_BYTES]):
            return True
    return False


def _marker_present(root: Path, marker) -> bool:
    """Is this marker satisfied here? A tuple means every part must be."""
    if isinstance(marker, tuple):
        return all(_marker_present(root, part) for part in marker)
    if "*" in marker:
        return any(root.glob(marker))
    return (root / marker).exists()


def _content_marker_label(root: Path, base: Path, marker) -> str:
    """The evidence, as the file and the header that proved it."""
    path_pattern, pattern = marker
    header = pattern.strip("^\\s*").split(":")[0].replace("\\*", "").strip("\\s* ")
    if "*" in path_pattern:
        import re as _re

        expression = _re.compile(pattern, _re.M | _re.I)
        for candidate in sorted(root.glob(path_pattern))[:20]:
            try:
                if candidate.is_file() and expression.search(
                        candidate.read_text(encoding="utf-8",
                                            errors="replace")[:_CONTENT_MARKER_BYTES]):
                    path_pattern = candidate.name
                    break
            except OSError:
                continue
    try:
        where = str((root / path_pattern).relative_to(base))
    except ValueError:  # pragma: no cover - root is always under base
        where = path_pattern
    return f"{where} -> {header}:"


def _marker_label(root: Path, base: Path, marker) -> str:
    """How the evidence reads in the report."""
    if isinstance(marker, tuple):
        return " + ".join(_marker_label(root, base, part) for part in marker)
    try:
        return str((root / marker).relative_to(base))
    except ValueError:  # pragma: no cover - root is always under base
        return str(marker)


#: `package.json` dependency names that identify a stack whose config file may
#: be absent or renamed. Read only when the manifest parses; a broken
#: `package.json` is not evidence of anything.
_DEPENDENCY_STACKS = {
    "next": "nextjs", "nuxt": "nuxt", "astro": "astro",
    "@sveltejs/kit": "sveltekit", "@angular/core": "angular",
    "gatsby": "gatsby", "vite": "vite",
    "@microsoft/sp-core-library": "spfx",
}


def _dependency_names(root: Path) -> set:
    manifest = root / "package.json"
    if not manifest.is_file():
        return set()
    try:
        data = json.loads(manifest.read_text(encoding="utf-8", errors="replace"))
    except (json.JSONDecodeError, OSError):
        return set()
    names: set = set()
    for section in ("dependencies", "devDependencies"):
        block = data.get(section)
        if isinstance(block, dict):
            names.update(block)
    return names


def detect(root: str | Path) -> Profile:
    """What this directory is, on the evidence in it.

    Marker files first, then `package.json` dependencies for the JavaScript
    stacks - a Next.js app whose config file is `next.config.mjs` is caught
    by the marker, and one that has none is caught by the dependency. Both
    record what they saw.

    Never raises: an unreadable directory is simply an undetected one, and an
    undetected one scans exactly the way it did before this module existed.
    """
    path = Path(root)
    profile = Profile(root=str(path))
    if not path.is_dir():
        return profile

    roots = _search_roots(path)
    for stack in STACKS:
        proof = ""
        for where in roots:
            for marker in stack.markers:
                try:
                    if _marker_present(where, marker):
                        proof = _marker_label(where, path, marker)
                        break
                except (OSError, ValueError):
                    continue
            if proof:
                break
        if not proof:
            # Content markers, for a stack whose proof is inside a file
            # rather than in its name. See `Stack.content_markers`.
            for where in roots:
                for marker in stack.content_markers:
                    try:
                        if _content_marker_present(where, marker):
                            proof = _content_marker_label(where, path, marker)
                            break
                    except (OSError, ValueError):
                        continue
                if proof:
                    break
        if not proof:
            for where in roots:
                dependencies = _dependency_names(where)
                if not dependencies:
                    continue
                for name, stack_name in _DEPENDENCY_STACKS.items():
                    if stack_name == stack.name and name in dependencies:
                        try:
                            rel = str((where / "package.json").relative_to(path))
                        except ValueError:  # pragma: no cover - path is under root
                            rel = "package.json"
                        proof = f"{rel} -> {name}"
                        break
                if proof:
                    break
        if proof:
            profile.stacks.append(stack)
            profile.evidence[stack.name] = proof
    return profile
